def sdpa_audio_forward(module,query,key,value,attention_mask,scaling,dropout=0.,**kwargs):
    # Matches transformers4.57 SDPA integration for this noncausal, non-GQA tower.
    out=F.scaled_dot_product_attention(query,key,value,attn_mask=attention_mask,dropout_p=dropout,is_causal=False,scale=scaling)
    return out.transpose(1,2).contiguous(),None
ALL_ATTENTION_FUNCTIONS={'sdpa':sdpa_audio_forward}

